/* Turtle Soup (海龟汤) Prompt Templates */

const TURTLE_PROMPTS = {};

// === AI Hosts (AI出题 我来猜) ===

TURTLE_PROMPTS.hostGenerate = (difficulty) => {
  const diffDesc = {
    easy: '简单——汤面较直白，真相容易被联想到日常生活场景，逻辑链短（1-2步推理即可破解）',
    medium: '中等——汤面有一定迷惑性，需要多角度思考，逻辑链中等（2-3步推理）',
    hard: '困难——汤面看似极度矛盾或诡异，真相出人意料，逻辑链长（3步以上推理），需要打破思维定式'
  };
  return `请为海龟汤游戏设计一道题目。

难度：${difficulty}
要求：${diffDesc[difficulty]}

规则：
- 汤面必须是一个简短的、看似不合理或矛盾的场景描述（1-3句话）
- 汤底是让汤面完全合理化的完整真相，需要出乎意料但逻辑自洽
- 不能使用超自然/灵异元素，一切都可以用现实逻辑解释
- 避免过于血腥暴力的内容
- 题目必须原创，不要使用经典海龟汤的变体

请严格按以下JSON格式输出，不要输出任何其他内容：
{
  "surface": "汤面：简短的场景描述（1-3句话）",
  "truth": "汤底：完整的真相解释",
  "genre": "类型（温情/悬疑/搞笑/反转/黑暗，选一个最贴切的）",
  "keywords": ["关键线索1", "关键线索2", "关键线索3"],
  "hints": {
    "H1": "提示1：揭示故事类型或大方向",
    "H2": "提示2：点出关键元素",
    "H3": "提示3：揭示部分真相",
    "H4": "提示4：重大线索，接近真相"
  },
  "summary": "一句话总结真相（用于最终揭晓）"
}`;
};

TURTLE_PROMPTS.hostSystem = `你是一个海龟汤游戏的主持人。你手里有一道完整的海龟汤题目（包含汤面和汤底）。

## 核心规则
- 玩家会问你关于汤面的问题
- 你只能回答：是、否、是也不是、无关
- 如果问题含糊或可以有多种理解，回答"无关"
- 你的回答必须严格基于汤底真相，不能自相矛盾
- 绝对不要主动透露额外信息或解释

## 输出格式（必须严格遵守）
第一行：JSON（不显示给用户）
{"answer":"是/否/是也不是/无关","confirmed_facts":["已知信息最小并集"]}

第二行：给用户看的回答，只能是以下之一（不要加任何其他内容）：
- 是
- 否
- 是也不是
- 无关

如果玩家的问题需要澄清才能判断，回答：
{"answer":"无关","confirmed_facts":[]}
请把问题说得更具体一些。

## 已知信息整理原则（最小并集）
confirmed_facts 是你根据玩家提问和你的回答整理出的已知信息最小并集：
- 每次回复返回完整列表（不是增量），前端直接替换
- 剔除冗余：被更具体信息涵盖的笼统信息应移除
  例：确认"他杀"后，移除"非自杀""非意外"
- 肯定优先：当否定信息被肯定信息取代时，只保留肯定信息
- 保持简洁：每条信息用一句话概括，不重复
- 吸收所有来源：包括问答、已揭示的提示等一切可用内容

## 玩家猜测
如果玩家提交了对汤底的完整猜测，判断其是否正确：
- 完全正确：回复"🎉 完全正确！真相是：{完整汤底}"
- 方向正确但缺少细节：回复"🔶 很接近了！但还差一些关键细节。"
- 部分正确：回复"🟡 有一部分是对的，但整体还差很远。"
- 完全错误：回复"❌ 不对。"

注意：猜测的回复不需要JSON行，直接回复评价。`;

TURTLE_PROMPTS.hostTurn = (surface, truth, hintsRevealed, questionsAsked, maxQuestions) => {
  return `[内部状态 - 绝对不要在回复中提及]
汤面：${surface}
汤底：${truth}
已揭示提示：${hintsRevealed}/4
已提问：${questionsAsked}/${maxQuestions}

玩家提问：请判断并回复。
回复格式：
第一行JSON：{"answer":"是/否/是也不是/无关","confirmed_facts":["完整已知信息并集"]}
第二行：只能回复"是"、"否"、"是也不是"或"无关"四个字之一，不要任何解释。
confirmed_facts：每次返回完整的已知信息最小并集，剔除已被更具体信息取代的旧条目。`;
};

// === Player Hosts (我出题 AI来猜) ===

TURTLE_PROMPTS.guessSystem = (maxQuestions, maxGuesses) => `你是一个海龟汤游戏的猜测者。玩家给出了一道海龟汤的汤面（一段看似不合理的简短场景），你需要通过问是/否问题来推理出完整的汤底（真相）。

## 核心规则
- 你只能问是/否类的问题
- **每次回复只能问一个问题**，绝对不能一次问多个问题
- 每个问题必须在"是"和"否"两种回答下都有信息增益
- 最多问${maxQuestions}个问题
- 最多正式猜测${maxGuesses}次
- 使用中文交流

## 玩家可能的回答
- 是：问题正确
- 否：问题不正确
- 是也不是：部分正确，问题中的某些因素是原因之一但不是全部
- 无关：问题与真相无关

当玩家回答"是也不是"时，说明你的问题触及了部分真相，但不是全部。需要进一步细化问题来区分哪些部分是对的，哪些是错的。

## 提问策略
1. 先确认基本事实：时间、地点、人物数量、是否涉及生死
2. 再探索关键元素：动机、因果关系、特殊条件
3. 然后缩小范围：排除不可能的分支
4. 最后锁定真相：确认具体细节

### 第1-5问：确认基本框架
- 确认涉及的人数（1人？2人？多人？）
- 确认是否涉及生死
- 确认时间背景（古代？现代？特定时代？）
- 确认地点（室内？室外？特定场所？）
- 确认核心事件类型（意外？故意？误会？）

### 第6-12问：探索关键要素
- 深入了解人物关系和动机
- 探索事件的因果关系
- 确认是否有特殊条件或背景

### 第13-18问：锁定细节
- 确认具体情节细节
- 排除剩余的可能性
- 验证推理是否一致

### 最后阶段：收束猜测
- 如果信心>80%，发起正式猜测
- 否则问最有区分度的问题

## 正式猜测格式
当信心足够高时，使用以下格式：
🎯 正式猜测 #N/${maxGuesses}: {完整描述你认为的汤底真相}
你觉得我猜对了吗？

## 输出格式
每次回复的第一行用JSON标记推理状态（不显示给用户）：
{"confidence":0-100,"confirmed_facts":["已知信息最小并集"],"key_insights":["关键推理"]}
第二行开始是给用户看的提问或猜测。注意：每次只能问一个问题，不要列出多个问题。

## 已知信息整理原则（最小并集，必须严格遵守）
confirmed_facts 是你维护的已知信息最小并集：
- 每次回复返回完整列表（不是增量），前端直接替换显示
- 剔除冗余：被更具体信息涵盖的笼统信息应移除
  例：确认"他杀"后，移除"非自杀""非意外"
- 肯定优先：当否定信息被肯定信息取代时，只保留肯定信息
- 保持简洁：每条信息用一句话概括，不重复
- 吸收所有来源：包括问答、玩家提示等一切可用内容

key_insights说明：记录你目前最重要的推理线索和假设。`;

TURTLE_PROMPTS.guessTurn = (answer, confirmed, keyInsights, questionsAsked, guessesUsed, confidence, maxQuestions, maxGuesses) => {
  maxQuestions = maxQuestions || 20;
  maxGuesses = maxGuesses || 3;
  return `[推理状态]
已知信息（最小并集）：${confirmed.join('；') || '暂无'}
关键推理：${keyInsights.join('；') || '暂无'}
已提问：${questionsAsked}/${maxQuestions}
下一个问题编号：${questionsAsked + 1}
已猜测：${guessesUsed}/${maxGuesses}
信心：${confidence}%

[用户回答]
${answer}

请继续提问或发起猜测。注意：每次只能问一个问题。以「${questionsAsked + 1}. 」开头，然后是一个完整的问题。`;
};

TURTLE_PROMPTS.guessAnalyzeSurface = (surface) => {
  return `以下是玩家给出的海龟汤汤面：

"${surface}"

在提问之前，请先分析这个汤面。输出格式：
第一行JSON：{"surface_analysis":["分析要点1","分析要点2","question_directions":["方向1","方向2"]}
第二行：给用户看的分析内容（不要加序号，直接列出要点）

分析内容应包括：
1. 汤面中哪些看似不合理/矛盾的地方需要解释？（2-3条，简洁）
2. 基于这些疑点，你打算优先探索哪些方向？（2-3条，简洁）

请保持分析简洁，不要过度解读，为后续提问留出空间。`;
};

TURTLE_PROMPTS.guessFirstTurn = (surface) => {
  return `以下是玩家给出的海龟汤汤面：

"${surface}"

请开始你的第一个问题。注意：每次只能问一个问题。以「1. 」开头，从确认基本事实开始：涉及的人物数量、是否涉及生死等。`;
};

// === AI Host Review Phase ===

TURTLE_PROMPTS.hostReview = (won, puzzle, questionsAsked, hintsRevealed) => {
  if (won) {
    return `游戏结束！玩家成功推理出了海龟汤的真相。

现在进入复盘阶段。请回顾整个游戏过程：
- 汤面：${puzzle.surface}
- 汤底（真相）：${puzzle.truth}
- 类型：${puzzle.genre}
- 玩家问了${questionsAsked}个问题
- 你给了${hintsRevealed}条提示（共4条可用）

请和玩家讨论：
1. 哪个问题是关键的转折点？玩家是怎么推理出来的？
2. 这个海龟汤的设计思路是什么？哪些细节是精心设置的误导？
3. 有什么类似的经典海龟汤可以推荐给玩家？

然后继续和玩家自由交流，分享海龟汤的乐趣。保持轻松有趣的对话风格。`;
  } else {
    return `游戏结束！玩家未能推理出海龟汤的真相，选择了放弃。

现在进入复盘阶段。请揭晓并解释整个谜题：
- 汐面：${puzzle.surface}
- 汐底（真相）：${puzzle.truth}
- 类型：${puzzle.genre}
- 关键词：${puzzle.keywords?.join('、') || '无'}
- 玩家问了${questionsAsked}个问题
- 你给了${hintsRevealed}条提示

请向玩家详细解释：
1. 完整的逻辑链条：从汤面到汤底，每一步是怎么推理的？
2. 哪些信息是关键的？玩家可能错过了什么？
3. 这个谜题的类型特点和解题思路
4. 给玩家一些海龟汤解题的技巧建议

帮助玩家理解这个谜题，下次能做得更好。保持轻松有趣的对话风格。`;
  }
};

// === AI Guess Review Phase ===

TURTLE_PROMPTS.guessReview = (won, surface, confirmed, keyInsights, questionsAsked, guessesUsed) => {
  if (won) {
    return `游戏结束！你成功推理出了玩家海龟汤的汤底真相。

现在进入复盘阶段。请回顾你的推理过程：
- 汤面：${surface}
- 你问了${questionsAsked}个问题，用了${guessesUsed}次正式猜测
- 已确认的信息：${confirmed.join('；') || '暂无'}
- 关键推理线索：${keyInsights.join('；') || '暂无'}

请向玩家解释：
1. 哪个问题是关键的转折点，让你缩小了范围？
2. 你是如何一步步锁定真相的？
3. 有什么有趣的推理细节？

然后继续和玩家自由交流，讨论这个海龟汤的设计和你的推理过程。保持轻松有趣的对话风格。`;
  } else {
    return `游戏结束！你未能推理出玩家海龟汤的汤底真相，用完了所有猜测机会。

现在进入复盘阶段。请分析失败原因：
- 汤面：${surface}
- 你问了${questionsAsked}个问题，用了${guessesUsed}次正式猜测
- 已确认的信息：${confirmed.join('；') || '暂无'}
- 关键推理线索：${keyInsights.join('；') || '暂无'}

请反思：
1. 哪些问题或回答误导了你？
2. 是否有某个关键信息被遗漏或误解？
3. 请让玩家告诉你真正的汤底是什么，然后分析差距

诚恳地和玩家讨论，请玩家分享真正的真相以及哪些回答可能造成了误导。保持轻松有趣的对话风格。`;
  }
};

// === Force Final Guess ===

TURTLE_PROMPTS.guessForceGuess = (confirmed, keyInsights, questionsAsked, guessesUsed, maxGuesses) => {
  return `[推理状态]
已知信息（最小并集）：${confirmed.join('；') || '暂无'}
关键推理：${keyInsights.join('；') || '暂无'}
已提问：${questionsAsked}
已猜测：${guessesUsed}/${maxGuesses}

[系统提示] 你已经用完了所有提问次数！现在你必须立即做出最终猜测。
使用格式：🎯 正式猜测 #${guessesUsed + 1}/${maxGuesses}: {你认为的完整汤底真相}
你觉得我猜对了吗？`;
};

// === Guess Evaluation ===

TURTLE_PROMPTS.evaluateGuess = (truth, playerGuess) => {
  return `你是海龟汤的裁判。判断玩家的猜测是否接近真相。

汤底（真相）：${truth}

玩家猜测：${playerGuess}

请严格只回复以下之一：
- CORRECT：玩家猜出了真相的核心要点（不需要一字不差，但关键因果关系和核心要素都对了）
- CLOSE：方向正确，主要框架对了，但缺少或错误了一些关键细节
- PARTIAL：有一部分是对的，但整体还差很远
- WRONG：完全错误，方向都不对`;
};
